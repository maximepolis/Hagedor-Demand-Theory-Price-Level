function R = sm_eval_node(nd, pg0, r, tau0, D0, dtau, dv, hh, rev)
% One node of the map.  Never throws: an unusable node returns a blank row
% with a status string, so a single infeasible corner cannot kill the run.
    R = sm_blank_row();
    R.mode    = nd.mode;
    R.rho     = nd.rho;
    R.sig     = nd.sig;
    R.bmult   = nd.bmult;
    R.btarget = nd.btarget;
    R.is_cal  = nd.is_cal;

    pg = pg0;
    pg.rho      = nd.rho;
    pg.sig_eps  = nd.sig;
    pg.sig_eps0 = nd.sig;
    % Rebuild the chain explicitly.  S_green rebuilds it itself whenever the
    % risk channel is on (phi_D > 0), from the same pg.rho and pg.sig_eps0, so
    % this is belt and braces for the phi_D = 0 case rather than a second
    % income process.
    [eG, PiD, stD] = make_income_process(pg);
    pg.eGrid = eG; pg.Pi = PiD; pg.stationary_e = stD;

    if strcmp(nd.mode, 'fixed-beta')
        pg.beta = pg0.beta * nd.bmult;
    else
        try
            [bstar, cout] = calibrate_beta(pg, r, nd.btarget, D0);
            pg.beta = bstar;
            if ~cout.converged
                R.status = 'beta-edge';
            end
        catch
            R.beta = NaN; R.status = 'beta-fail';
            return;
        end
    end
    R.beta = pg.beta;
    if pg.beta * (1 + r) >= pg.betaR_max
        R.status = 'beta-bound';
        return;
    end

    % ---- baseline ----
    [S0, o0] = S_green(r, tau0, D0, pg);
    if ~(isfinite(S0) && S0 > 0 && o0.feasible)
        R.status = sm_cat_status(R.status, 'base-infeasible');
        return;
    end
    R.S0     = S0;
    R.gini_a = o0.gini_a;
    R.cmass  = sum(o0.dist(1, :));
    if isfield(o0, 'hhdiag') && isfield(o0.hhdiag, 'err'),   R.hh_err   = o0.hhdiag.err;   end
    if isfield(o0, 'distdiag') && isfield(o0.distdiag, 'err'), R.dist_err = o0.distdiag.err; end
    if isfield(o0, 'hhdiag') && isfield(o0.hhdiag, 'euler_max_log10')
        R.euler_max_log10 = o0.hhdiag.euler_max_log10;
    end

    % ---- lump-sum step: the sign-map headline ----
    [S1, o1] = S_green(r, tau0 + dtau, D0, pg);
    if ~(isfinite(S1) && S1 > 0 && o1.feasible)
        R.status = sm_cat_status(R.status, 'ls-infeasible');
        return;
    end
    R.eps_ls     = (log(S1) - log(S0)) / dtau;
    R.eps_ls_lin = (S1 - S0) / (S0 * dtau);
    dS_pol = sum(sum((o1.polA - o0.polA) .* o0.dist));
    dS_dst = sum(sum(o1.polA .* (o1.dist - o0.dist)));
    R.dir_ls   = dS_pol / (S0 * dtau);
    R.dst_ls   = dS_dst / (S0 * dtau);
    R.recon_ls = (S1 - S0) - (dS_pol + dS_dst);
    if abs(S1 - S0) > 0
        R.share_dist_ls = dS_dst / (S1 - S0);
    end

    % ---- half-step, for finite-difference stability ----
    [S1h, o1h] = S_green(r, tau0 + dtau/2, D0, pg);
    if isfinite(S1h) && S1h > 0 && o1h.feasible
        e_half   = (log(S1h) - log(S0)) / (dtau/2);
        R.fd_stab = abs(R.eps_ls - e_half) / max(abs(R.eps_ls), eps);
    end

    % ---- mean-zero regressive tilt, and its direct covariance term ----
    % Construction copied from audit_tax_incidence BLOCK B: a uniform tax of
    % one unit of revenue plus a proportional subsidy of the same revenue, so
    % the net income change dv*(y_i - ybar) has mean zero over the baseline
    % distribution.
    pgT = pg; pgT.vartheta = -dv;
    [S1t, o1t] = S_green(r, tau0 + rev, D0, pgT);
    if isfinite(S1t) && S1t > 0 && o1t.feasible
        R.eps_tilt = (log(S1t) - log(S0)) / rev;
        dS_polT = sum(sum((o1t.polA - o0.polA) .* o0.dist));
        dS_dstT = sum(sum(o1t.polA .* (o1t.dist - o0.dist)));
        R.dir_tilt   = dS_polT / (S0 * rev);
        R.dst_tilt   = dS_dstT / (S0 * rev);
        R.recon_tilt = (S1t - S0) - (dS_polT + dS_dstT);
        if abs(S1t - S0) > 0
            R.share_dist_tilt = dS_dstT / (S1t - S0);
        end
    else
        R.status = sm_cat_status(R.status, 'tilt-infeasible');
    end

    [Sbh, obh] = S_green(r, tau0 - hh, D0, pg);
    if isfinite(Sbh) && obh.feasible
        mb    = (obh.polA - o0.polA) / hh;            % d a'/d y^net, node by node
        yeff  = o0.eGrid_eff(:);
        wy    = sum(o0.dist, 1)';
        ybar  = wy' * yeff;
        dynet = dv * (yeff - ybar);
        dS_cov = sum((mb * diag(dynet)) .* o0.dist, 'all');
        R.cov_tilt = dS_cov / (S0 * rev);
        R.Edy      = wy' * dynet;                     % mean-zero check
    else
        R.status = sm_cat_status(R.status, 'cov-skipped');
    end

    % ---- mobility, from the shared function ----
    try
        M = kv_wealth_mobility(o0.dist, o0.polA, pg.aGrid(:), o0.Pi_eff, ...
                               struct('nbin', 5, 'horizon', 200));
        R.mob_shorrocks = M.shorrocks;
        R.mob_ret1      = M.retention(1);
        R.mob_retK      = M.retention(end);
        R.mob_up1       = M.up1;
        R.mob_down1     = M.down1;
        R.mob_halflife  = M.halflife;
    catch
        R.status = sm_cat_status(R.status, 'mobility-failed');
    end

    R.conv = isfinite(R.eps_ls);
    if isempty(R.status), R.status = 'ok'; end
end

