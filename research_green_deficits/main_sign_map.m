% Canonical field set and order.  Every branch of sm_eval_node returns THIS
% struct, so the rows concatenate into a struct array without a field-order
% error.
    R = struct( ...
        'mode', '', 'rho', NaN, 'sig', NaN, 'bmult', NaN, 'btarget', NaN, ...
        'beta', NaN, 'is_cal', false, ...
        'S0', NaN, 'gini_a', NaN, 'cmass', NaN, ...
        'eps_ls', NaN, 'eps_ls_lin', NaN, 'dir_ls', NaN, 'dst_ls', NaN, ...
        'share_dist_ls', NaN, 'recon_ls', NaN, 'fd_stab', NaN, ...
        'eps_tilt', NaN, 'dir_tilt', NaN, 'dst_tilt', NaN, ...
        'share_dist_tilt', NaN, 'recon_tilt', NaN, 'cov_tilt', NaN, 'Edy', NaN, ...
        'mob_shorrocks', NaN, 'mob_ret1', NaN, 'mob_retK', NaN, ...
        'mob_up1', NaN, 'mob_down1', NaN, 'mob_halflife', NaN, ...
        'hh_err', NaN, 'dist_err', NaN, 'euler_max_log10', NaN, ...
        'conv', false, 'status', '');
end

