% -------------------------------------------------------------------------
function PAR = sm_parity_gate(projdir, N, na_here)
% Compare the calibrated node against what the certified drivers stored.
% The gate is INFORMATIONAL when the stored run used a different grid: the
% stored .mat files do not all record their na, so a gap is a prompt to check,
% not by itself a failure.
    PAR = struct('name', {}, 'here', {}, 'stored', {}, 'gap', {}, 'verdict', {});
    ic = find([N.is_cal] & [N.conv], 1, 'first');
    if isempty(ic)
        PAR(end+1) = struct('name', 'calibrated node', 'here', NaN, ...
            'stored', NaN, 'gap', NaN, ...
            'verdict', 'NOT AVAILABLE: the calibrated node did not converge');
        return;
    end
    tol = 5e-2;   % relative; the certified runs and this one may differ in na

    f1 = fullfile(projdir, 'output', 'tax_elasticity_results.mat');
    if exist(f1, 'file') == 2
        A = load(f1);
        if isfield(A, 'eps_ls')
            PAR(end+1) = sm_par_row('eps_ls vs decompose_tax_elast', ...
                N(ic).eps_ls, A.eps_ls, tol);
        end
        if isfield(A, 'eps_tilt')
            PAR(end+1) = sm_par_row('eps_tilt vs decompose_tax_elast', ...
                N(ic).eps_tilt, A.eps_tilt, tol);
        end
        if isfield(A, 'cov_perRev')
            % EXPECTED SMALL GAP, not drift: decompose_tax_elasticity measures
            % the marginal propensity at the same-revenue LEVY base
            % (vartheta = +dv), whereas audit_tax_incidence BLOCK B -- which
            % this driver follows -- measures it at the vartheta = 0 base.
            % Different base, same object to first order.  The audit row below
            % is the like-for-like comparison; this one is a cross-check.
            PAR(end+1) = sm_par_row('cov_tilt vs decompose (LEVY base)', ...
                N(ic).cov_tilt, A.cov_perRev, tol);
        end
    else
        PAR(end+1) = struct('name', 'tax_elasticity_results.mat', 'here', NaN, ...
            'stored', NaN, 'gap', NaN, ...
            'verdict', 'ABSENT: run decompose_tax_elasticity to enable this gate');
    end

    f2 = fullfile(projdir, 'output', 'audit_tax_incidence.mat');
    if exist(f2, 'file') == 2
        B = load(f2);
        if isfield(B, 'AU') && isfield(B.AU, 'blockB') && isfield(B.AU.blockB, 'per_rev')
            pr = B.AU.blockB.per_rev;
            if isfield(pr, 'pol')
                PAR(end+1) = sm_par_row('dir_tilt vs audit BLOCK B', ...
                    N(ic).dir_tilt, pr.pol, tol);
            end
            if isfield(pr, 'dist')
                PAR(end+1) = sm_par_row('dst_tilt vs audit BLOCK B', ...
                    N(ic).dst_tilt, pr.dist, tol);
            end
            if isfield(pr, 'cov')
                PAR(end+1) = sm_par_row('cov_tilt vs audit BLOCK B', ...
                    N(ic).cov_tilt, pr.cov, tol);
            end
            if isfield(pr, 'total')
                PAR(end+1) = sm_par_row('eps_tilt vs audit BLOCK B', ...
                    N(ic).eps_tilt, pr.total, tol);
            end
        end
    else
        PAR(end+1) = struct('name', 'audit_tax_incidence.mat', 'here', NaN, ...
            'stored', NaN, 'gap', NaN, ...
            'verdict', 'ABSENT: run audit_tax_incidence to enable this gate');
    end

    PAR(end+1) = struct('name', 'grid of this run (na)', 'here', na_here, ...
        'stored', NaN, 'gap', NaN, ...
        'verdict', 'stored runs do not all record na; compare grids by hand');
end

% -------------------------------------------------------------------------
function p = sm_par_row(name, here, stored, tol)
    gap = here - stored;
    if ~isfinite(here) || ~isfinite(stored)
        v = 'NOT COMPARABLE (one side missing)';
    elseif abs(gap) <= tol * max(abs(stored), 1)
        v = 'agrees within tolerance';
    else
        v = 'GAP: investigate before quoting either number';
    end
    p = struct('name', name, 'here', here, 'stored', stored, 'gap', gap, ...
               'verdict', v);
end

