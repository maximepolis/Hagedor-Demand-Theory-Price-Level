        jc = find(strcmp({N.mode}, MODES{m}) & [N.is_cal], 1, 'first');
        if ~isempty(jc)
            hold on; plot(N(jc).rho, N(jc).sig, 'ko', 'MarkerSize', 12, ...
                          'LineWidth', 1.6);
        end
    end
end

% -------------------------------------------------------------------------
function pg = sm_rebuild_grid(pg)
    u = linspace(0, 1, pg.na)';
    pg.aGrid = -pg.abar + (pg.amax + pg.abar) * (u.^pg.acurv);
    pg.aGrid(1) = -pg.abar; pg.aGrid(end) = pg.amax;
end

% -------------------------------------------------------------------------
function s = sm_sgn(x)
    if ~isfinite(x),   s = 'n/a';
    elseif x > 0,      s = '+';
    elseif x < 0,      s = '-';
    else,              s = '0';
    end
end

% -------------------------------------------------------------------------
function s = sm_third_str(row)
    if isfinite(row.bmult)
        s = sprintf('b*%.2f', row.bmult);
    elseif isfinite(row.btarget)
        s = sprintf('bT%.2f', row.btarget);
    else
        s = '--';
    end
end

% -------------------------------------------------------------------------
function s = sm_num2s(x, fmt)
% Scalar formatter that prints a dash rather than 'NaN' for an empty slot, so
% an unfilled empirical range never reads as a measured zero.
    if isempty(x) || ~isfinite(x)
        s = '--';
    else
        s = sprintf(fmt, x);
    end
end

% -------------------------------------------------------------------------
function s = sm_list2s(c)
% Comma-joined cell of char, or an explicit '(none)'.
    if isempty(c), s = '(none)'; else, s = strjoin(c, ', '); end
end

% -------------------------------------------------------------------------
function s = sm_tern(c, a, b)
    if c, s = a; else, s = b; end
end

% -------------------------------------------------------------------------
function sm_tee(fid, varargin)
    fprintf(varargin{:}); fprintf(fid, varargin{:});
end
